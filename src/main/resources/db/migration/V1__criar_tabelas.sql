-- V1: estrutura inicial do banco da EduLib API

CREATE TABLE tb_livro (
    id_livro            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo              VARCHAR(255),
    autor               VARCHAR(255),
    quantidade_estoque  INTEGER,
    isbn                VARCHAR(255)
);

CREATE TABLE tb_cliente (
    id_aluno     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula    VARCHAR(255) NOT NULL,
    nome_aluno   VARCHAR(255),
    idade_aluno  INTEGER,
    CONSTRAINT uk_cliente_matricula UNIQUE (matricula)
);

CREATE TABLE tb_emprestimo (
    id_emprestimo            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_emprestimo          DATE,
    data_devolucao_prevista  DATE,
    data_devolucao_real      DATE,
    multa_cobrada            NUMERIC(38, 2),
    status                   VARCHAR(255),
    id_aluno                 BIGINT,
    CONSTRAINT fk_emprestimo_aluno
        FOREIGN KEY (id_aluno) REFERENCES tb_cliente (id_aluno)
);

CREATE TABLE tb_emprestimoitemmodel (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_emprestimo  BIGINT,
    id_livro       BIGINT,
    CONSTRAINT fk_item_emprestimo
        FOREIGN KEY (id_emprestimo) REFERENCES tb_emprestimo (id_emprestimo),
    CONSTRAINT fk_item_livro
        FOREIGN KEY (id_livro) REFERENCES tb_livro (id_livro)
);